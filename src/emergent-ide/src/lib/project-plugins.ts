import { access, cp, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { parse, stringify } from "smol-toml";
import { engineRoot } from "./workspace";

/** A plugin listed under `[[plugins]]` in emergent.toml, read from its `plugin.toml`. */
export type ProjectPluginInfo = {
  id: string;
  name: string;
  version: string;
  description: string;
  /** Project-relative plugin folder. */
  path: string;
  crate: string | null;
  /** Asset roots relative to the plugin folder. */
  assetRoots: string[];
  /** Set when the entry or its plugin.toml cannot be read; the engine refuses to load the project. */
  error?: string;
};

export class PluginError extends Error {
  constructor(message: string, readonly status = 400) { super(message); }
}

/** Source of new plugins; improvements to new-plugin defaults belong in this folder. */
const pluginTemplate = path.join(engineRoot, "templates/plugin");
const TEMPLATE_ID = "template.plugin";
/** IDE-created ids: lowercase segments starting with a letter (the engine accepts digits first). */
const NEW_PLUGIN_ID = /^(?!emergent\.|project\.)[a-z][a-z0-9_]*(\.[a-z][a-z0-9_]*)+$/;

const table = (value: unknown): Record<string, unknown> => value && typeof value === "object" && !Array.isArray(value) ? value as Record<string, unknown> : {};
const text = (value: unknown) => typeof value === "string" ? value : "";

function relativeFolder(value: unknown) {
  const folder = text(value);
  if (!folder || path.isAbsolute(folder) || folder.includes("\\") || folder.split("/").some(part => !part || part === "." || part === "..")) return null;
  return folder;
}

export async function readProjectPlugins(root: string): Promise<ProjectPluginInfo[]> {
  let manifest: Record<string, unknown>;
  try { manifest = parse(await readFile(path.join(root, "emergent.toml"), "utf8")); } catch { return []; }
  const entries = Array.isArray(manifest.plugins) ? manifest.plugins.map(table) : [];
  return Promise.all(entries.map(async entry => {
    const id = text(entry.id), folder = relativeFolder(entry.path);
    const info: ProjectPluginInfo = { id, name: id, version: "", description: "", path: folder ?? text(entry.path), crate: null, assetRoots: [] };
    if (!folder) return { ...info, error: "Plugin path must be a project-relative folder." };
    try {
      const plugin = parse(await readFile(path.join(root, folder, "plugin.toml"), "utf8"));
      const assetRoots = (Array.isArray(plugin.asset_roots) ? plugin.asset_roots : []).map(relativeFolder);
      if (assetRoots.some(item => !item)) return { ...info, error: "plugin.toml asset roots must be relative folders." };
      return { ...info, name: text(plugin.name) || id, version: text(plugin.version), description: text(plugin.description), crate: text(plugin.crate) || null, assetRoots: assetRoots as string[], ...(plugin.id !== id ? { error: `plugin.toml declares id '${text(plugin.id)}'.` } : {}) };
    } catch (error) {
      return { ...info, error: `Cannot read plugin.toml: ${error instanceof Error ? error.message : String(error)}` };
    }
  }));
}

export const pluginCrate = (id: string) => id.replace(/[._]/g, "-");

/** `src/generated/plugins.rs`: every listed plugin that has code, in emergent.toml order. */
export function generatedPluginsSource(plugins: ProjectPluginInfo[]) {
  const lines = plugins.filter(plugin => plugin.crate && !plugin.error).map(plugin => `    &${plugin.crate!.replace(/-/g, "_")}::PLUGIN,`);
  return `//! Generated by the Emergent IDE from \`[[plugins]]\` in emergent.toml; do not edit.\npub static PLUGINS: &[&dyn emergent::Plugin] = &[${lines.length ? `\n${lines.join("\n")}\n` : ""}];\n`;
}

async function exists(file: string) { try { await access(file); return true; } catch { return false; } }

/** Creates `plugins/<id>` from the plugin template and wires it into emergent.toml, Cargo.toml and the generated list. */
export async function createPlugin(project: { root: string }, input: { id?: unknown; name?: unknown }) {
  const id = text(input.id).trim(), name = text(input.name).trim();
  const publisher = id.split(".")[0];
  if (id.includes(".") && (publisher === "emergent" || publisher === "project")) throw new PluginError(`Plugin id cannot start with '${publisher}.': that prefix is reserved for ${publisher === "emergent" ? "engine built-ins" : "the game's own components"}. Use your own publisher name, e.g. studio.${id.slice(publisher.length + 1)}.`);
  if (!NEW_PLUGIN_ID.test(id) || id.length > 64) throw new PluginError("Plugin id must look like publisher.name: lowercase letters, digits and _, each part starting with a letter.");
  if (!name || name.length > 64 || /[\u0000-\u001f]/.test(name)) throw new PluginError("Plugin name needs 1–64 printable characters.");
  const plugins = await readProjectPlugins(project.root);
  if (plugins.some(plugin => plugin.id === id)) throw new PluginError(`Plugin '${id}' is already in this project.`, 409);
  const folder = `plugins/${id}`, target = path.join(project.root, folder), crate = pluginCrate(id);
  if (await exists(target)) throw new PluginError(`${folder} already exists.`, 409);

  const manifestPath = path.join(project.root, "emergent.toml"), cargoPath = path.join(project.root, "Cargo.toml");
  const manifestSource = await readFile(manifestPath, "utf8"), cargoSource = await readFile(cargoPath, "utf8");
  const generatedRoot = relativeFolder(parse(manifestSource).generated_code) ?? "src/generated";
  const generatedPath = path.join(project.root, generatedRoot, "plugins.rs");
  const generatedBefore = await readFile(generatedPath, "utf8").catch(() => null);
  const cargo = parse(cargoSource) as Record<string, unknown>, dependencies = table(cargo.dependencies);
  if (dependencies[crate]) throw new PluginError(`Cargo.toml already depends on ${crate}.`, 409);
  const engine = table(dependencies.emergent);
  if (typeof engine.path !== "string") throw new PluginError("This project's Cargo.toml has no path dependency on emergent.");

  try {
    await cp(pluginTemplate, target, { recursive: true, errorOnExist: true, force: false, filter: source => path.basename(source) !== "target" });
    const pluginToml = parse(await readFile(path.join(target, "plugin.toml"), "utf8"));
    Object.assign(pluginToml, { id, name, version: "0.1.0", description: "", crate });
    await writeFile(path.join(target, "plugin.toml"), stringify(pluginToml) + "\n");
    const pluginCargo = parse(await readFile(path.join(target, "Cargo.toml"), "utf8")) as Record<string, unknown>;
    table(pluginCargo.package).name = crate;
    // Same engine crate as the game, so both resolve to one `emergent` package.
    const engineDir = path.resolve(project.root, engine.path), relative = path.relative(target, engineDir);
    table(table(pluginCargo.dependencies).emergent).path = path.isAbsolute(engine.path) ? engineDir : relative;
    await writeFile(path.join(target, "Cargo.toml"), stringify(pluginCargo) + "\n");
    const lib = path.join(target, "src/lib.rs");
    await writeFile(lib, (await readFile(lib, "utf8")).replaceAll(TEMPLATE_ID, id));

    cargo.dependencies = { ...dependencies, [crate]: { path: folder } };
    await writeFile(cargoPath, stringify(cargo) + "\n");
    await writeFile(manifestPath, `${manifestSource.trimEnd()}\n\n[[plugins]]\nid = ${JSON.stringify(id)}\npath = ${JSON.stringify(folder)}\n`);
    await writeFile(generatedPath, generatedPluginsSource(await readProjectPlugins(project.root)));
  } catch (error) {
    // Leave the project as it was: one plugin is either fully added or not at all.
    await Promise.allSettled([
      rm(target, { recursive: true, force: true }),
      writeFile(manifestPath, manifestSource),
      writeFile(cargoPath, cargoSource),
      generatedBefore === null ? rm(generatedPath, { force: true }) : writeFile(generatedPath, generatedBefore),
    ]);
    throw error;
  }
  const main = await readFile(path.join(project.root, "src/main.rs"), "utf8").catch(() => "");
  const wired = main.includes("generated::plugins::PLUGINS");
  return {
    plugin: (await readProjectPlugins(project.root)).find(plugin => plugin.id === id)!,
    warning: wired ? null : `src/main.rs does not return generated::plugins::PLUGINS from ProjectGame::plugins(); add \`mod generated;\` with \`pub mod plugins;\` and that override, then rebuild.`,
  };
}
