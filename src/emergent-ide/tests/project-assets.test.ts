import assert from "node:assert/strict";
import test from "node:test";
import { mkdir, mkdtemp, readFile, rm, symlink, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { parse } from "smol-toml";
import { createProjectAsset, deleteProjectAsset } from "../src/lib/project-assets";
import { scenePlacement } from "../src/lib/scene-placement";
import { readProjectSnapshot } from "../src/lib/project";

test("asset creation optionally includes instances, preserves comments, and retains assets on failed inclusion", async (t) => {
  const root = await mkdtemp(path.join(os.tmpdir(), "emergent-assets-"));
  const previousRoot = process.env.EMERGENT_PROJECT_PATH;
  const previousData = process.env.EMERGENT_IDE_DATA_DIR;
  process.env.EMERGENT_PROJECT_PATH = root;
  process.env.EMERGENT_IDE_DATA_DIR = path.join(root, ".data");
  t.after(async () => {
    if (previousRoot === undefined) delete process.env.EMERGENT_PROJECT_PATH; else process.env.EMERGENT_PROJECT_PATH = previousRoot;
    if (previousData === undefined) delete process.env.EMERGENT_IDE_DATA_DIR; else process.env.EMERGENT_IDE_DATA_DIR = previousData;
    await rm(root, { recursive: true, force: true });
  });

  await mkdir(path.join(root, "assets"));
  await mkdir(path.join(root, "src"));
  await writeFile(path.join(root, "emergent.toml"), 'id="test"\nname="Test"\nasset_roots=["assets"]\nentry_scene="assets/main.scene.toml"');
  const target = path.join(root,"assets/main.scene.toml");
  await writeFile(target, '# keep this authored note\nschema_version=1\nid="main"\nentities=[]\n');
  const project = await readProjectSnapshot();
  // Use the project's declared root while preserving the template-relative contract.
  project.assetRoots = ["assets"];
  const first = await createProjectAsset(project,"object.cube","First cube","assets/main.scene.toml");
  assert.equal(first.sceneError,undefined);
  let source = await readFile(target,"utf8");
  assert.ok(source.startsWith("# keep this authored note"));
  const entries = parse(source).entities as { id: string; asset: string }[];
  assert.equal(entries.length,1);
  assert.match(first.id,/^[a-f0-9-]{36}$/);
  assert.equal(entries[0].id,first.id);
  assert.equal(entries[0].asset,first.path);
  const definition = parse(await readFile(path.join(root,first.path),"utf8"));
  assert.equal(definition.id,first.id);
  assert.equal(definition.name,"First cube");
  await createProjectAsset(project,"light.point","Lamp","assets/main.scene.toml");
  source = await readFile(target,"utf8");
  assert.equal((parse(source).entities as unknown[]).length,2);
  const duplicate = await createProjectAsset(project,"object.cube","First cube","assets/main.scene.toml");
  assert.equal(duplicate.sceneError,undefined);
  assert.notEqual(duplicate.id,first.id);
  assert.notEqual(duplicate.path,first.path);
  const placement = await scenePlacement(project,"assets/main.scene.toml");
  const cubes = placement.instances.filter(instance=>instance.name==="First cube");
  assert.deepEqual(cubes.map(instance=>instance.id),[first.id,duplicate.id]);
  const refreshed = await readProjectSnapshot();
  assert.equal(refreshed.files.find(file=>file.path===first.path)?.displayName,"First cube");
  assert.equal(refreshed.files.find(file=>file.path===duplicate.path)?.displayName,"First cube");
  const unicode = await createProjectAsset(project,"object.cube","立方体");
  assert.equal(parse(await readFile(path.join(root,unicode.path),"utf8")).name,"立方体");
  const newScene = await createProjectAsset(project,"scene.blank","Forest clearing");
  const sceneDefinition = parse(await readFile(path.join(root,newScene.path),"utf8"));
  assert.equal(sceneDefinition.name,"Forest clearing");
  assert.deepEqual(sceneDefinition.entities,[]);
  assert.equal((await readProjectSnapshot()).files.some(file=>file.path===newScene.path),true);
  const camera = await createProjectAsset(project,"camera.perspective","Gameplay camera","assets/main.scene.toml");
  assert.equal(camera.sceneError,undefined);
  const cameraScene = parse(await readFile(target,"utf8"));
  assert.equal(cameraScene.active_camera,camera.id);
  assert.equal((cameraScene.entities as { id:string }[]).some(entity=>entity.id===camera.id),true);
  assert.equal((parse(await readFile(path.join(root,camera.path),"utf8")).camera as {projection:string}).projection,"perspective");
  await assert.rejects(createProjectAsset(project,"object.cube","../escape"),/Use letters/);
  await writeFile(target,'schema_version=99\nid="main"\nentities=[]');
  const failed = await createProjectAsset(project,"object.pyramid","Kept pyramid","assets/main.scene.toml");
  assert.match(failed.sceneError!,/Asset saved, but not included/);
  assert.match(await readFile(path.join(root,failed.path),"utf8"),/primitive = "pyramid"/);
  assert.match(await readFile(target,"utf8"),/schema_version=99/);
  await rm(path.join(root,"assets/entities"),{ recursive:true });
  await symlink(os.tmpdir(),path.join(root,"assets/entities"));
  await assert.rejects(createProjectAsset(project,"object.cube","Escape"),/symbolic links/);
});

test("project asset deletion is restricted to unreferenced files under declared asset roots",async t=>{
  const root=await mkdtemp(path.join(os.tmpdir(),"emergent-asset-delete-"));
  const previousRoot=process.env.EMERGENT_PROJECT_PATH;
  t.after(async()=>{
    if(previousRoot===undefined)delete process.env.EMERGENT_PROJECT_PATH;else process.env.EMERGENT_PROJECT_PATH=previousRoot;
    await rm(root,{recursive:true,force:true});
  });
  process.env.EMERGENT_PROJECT_PATH=root;
  await mkdir(path.join(root,"assets"));
  await mkdir(path.join(root,"src"));
  await writeFile(path.join(root,"emergent.toml"),'id="delete-test"\nname="Delete Test"\nasset_roots=["assets"]\nentry_scene="assets/main.scene.toml"\n');
  await writeFile(path.join(root,"assets/main.scene.toml"),'schema_version=1\nid="main"\nentities=[]\n');
  await writeFile(path.join(root,"assets/referenced.png"),Buffer.from([1,2,3]));
  await writeFile(path.join(root,"assets/free.bin"),Buffer.from([4,5,6]));
  await writeFile(path.join(root,"assets/reference.entity.toml"),'schema_version=1\nid="reference"\nimage="assets/referenced.png"\n');
  const project=await readProjectSnapshot();
  await assert.rejects(deleteProjectAsset(project,"assets/main.scene.toml"),/entry scene/);
  await assert.rejects(deleteProjectAsset(project,"assets/referenced.png"),/referenced by assets\/reference.entity.toml/);
  await deleteProjectAsset(project,"assets/free.bin");
  await assert.rejects(readFile(path.join(root,"assets/free.bin")),{code:"ENOENT"});
  await assert.rejects(deleteProjectAsset(project,"../secret"),/Invalid project asset path/);
});
