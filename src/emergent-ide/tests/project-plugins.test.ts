import assert from "node:assert/strict";
import { cp, mkdtemp, readFile, rm, stat, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import test from "node:test";
import { parse } from "smol-toml";
import { createPlugin, generatedPluginsSource, readProjectPlugins } from "../src/lib/project-plugins";
import { engineRoot } from "../src/lib/workspace";

async function templateProject() {
  const root = await mkdtemp(path.join(os.tmpdir(), "emergent-plugins-"));
  await cp(path.join(engineRoot, "templates/standard"), root, { recursive: true, filter: source => path.basename(source) !== "target" });
  const cargo = await readFile(path.join(root, "Cargo.toml"), "utf8");
  await writeFile(path.join(root, "Cargo.toml"), cargo.replace(`path = "../.."`, `path = ${JSON.stringify(engineRoot)}`) + "\n[workspace]\n");
  return root;
}

test("createPlugin copies the template and wires manifest, Cargo and generated list", async () => {
  const root = await templateProject();
  try {
    const { plugin, warning } = await createPlugin({ root }, { id: "acme.beans", name: "Beans" });
    assert.equal(warning, null);
    assert.deepEqual([plugin.id, plugin.name, plugin.version, plugin.crate, plugin.path, plugin.assetRoots], ["acme.beans", "Beans", "0.1.0", "acme-beans", "plugins/acme.beans", ["assets"]]);
    const lib = await readFile(path.join(root, "plugins/acme.beans/src/lib.rs"), "utf8");
    assert.match(lib, /"acme\.beans\.drift"/);
    assert.doesNotMatch(lib, /template\.plugin/);
    const pluginCargo = parse(await readFile(path.join(root, "plugins/acme.beans/Cargo.toml"), "utf8")) as { package: { name: string }; dependencies: { emergent: { path: string } } };
    assert.equal(pluginCargo.package.name, "acme-beans");
    assert.equal(pluginCargo.dependencies.emergent.path, engineRoot);
    const cargo = parse(await readFile(path.join(root, "Cargo.toml"), "utf8")) as { dependencies: Record<string, { path?: string }> };
    assert.equal(cargo.dependencies["acme-beans"].path, "plugins/acme.beans");
    assert.deepEqual(await readProjectPlugins(root), [plugin]);
    assert.match(await readFile(path.join(root, "src/generated/plugins.rs"), "utf8"), /&acme_beans::PLUGIN,/);

    await assert.rejects(createPlugin({ root }, { id: "acme.beans", name: "Again" }), /already in this project/);
    await assert.rejects(createPlugin({ root }, { id: "emergent.airports", name: "Bad" }), /reserved for engine built-ins.*studio\.airports/);
    await assert.rejects(createPlugin({ root }, { id: "project.beans", name: "Bad" }), /reserved for the game's own components/);
    for (const id of ["beans", "Acme.beans", "acme.1beans", "acme..beans"]) {
      await assert.rejects(createPlugin({ root }, { id, name: "Bad" }), /publisher\.name/, id);
    }
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("createPlugin leaves the project untouched when a step fails", async () => {
  const root = await templateProject();
  try {
    const manifest = await readFile(path.join(root, "emergent.toml"), "utf8"), cargo = await readFile(path.join(root, "Cargo.toml"), "utf8");
    // The generated list cannot be written into a missing folder, so creation fails after editing the manifests.
    await rm(path.join(root, "src/generated"), { recursive: true });
    await assert.rejects(createPlugin({ root }, { id: "acme.beans", name: "Beans" }));
    assert.equal(await readFile(path.join(root, "emergent.toml"), "utf8"), manifest);
    assert.equal(await readFile(path.join(root, "Cargo.toml"), "utf8"), cargo);
    await assert.rejects(stat(path.join(root, "plugins/acme.beans")));
  } finally { await rm(root, { recursive: true, force: true }); }
});

test("readProjectPlugins reports bad entries instead of throwing", async () => {
  const root = await templateProject();
  try {
    const manifest = await readFile(path.join(root, "emergent.toml"), "utf8");
    await writeFile(path.join(root, "emergent.toml"), `${manifest}\n[[plugins]]\nid = "acme.gone"\npath = "plugins/acme.gone"\n\n[[plugins]]\nid = "acme.out"\npath = "../outside"\n`);
    const [gone, outside] = await readProjectPlugins(root);
    assert.match(gone.error ?? "", /plugin\.toml/);
    assert.match(outside.error ?? "", /project-relative/);
    assert.equal(generatedPluginsSource([gone, outside]), "//! Generated by the Emergent IDE from `[[plugins]]` in emergent.toml; do not edit.\npub static PLUGINS: &[&dyn emergent::Plugin] = &[];\n");
  } finally { await rm(root, { recursive: true, force: true }); }
});
